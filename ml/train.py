import csv

from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error

WINDOW = 10
AHEAD = 10


def features(window):
    now = window[-1]
    change = window[-1] - window[0]
    return [now, change]


def load():
    recordings = []
    last_time = None

    with open("server/bpm_log.csv") as f:
        for row in csv.reader(f):
            timestamp = float(row[0])
            bpm = int(row[1])

            if last_time is None or timestamp - last_time > 5:
                recordings.append([])

            recordings[-1].append(bpm)
            last_time = timestamp

    # Throw away tiny recordings (under 30 seconds), e.g. when your finger slipped for a moment
    long_recordings = []
    for recording in recordings:
        if len(recording) >= 30:
            long_recordings.append(recording)
    return long_recordings


def make_xy(recordings):
    X = []
    y = []
    for bpms in recordings:
        for start in range(len(bpms) - WINDOW - AHEAD + 1):
            window = bpms[start:start + WINDOW]
            newest = start + WINDOW - 1
            X.append(features(window))
            y.append(bpms[newest + AHEAD])
    return X, y


def train(X_train, y_train):
    model = LinearRegression().fit(X_train, y_train)
    return model


def test(model, X_test, y_test):
    model_guesses = model.predict(X_test)
    model_error = mean_absolute_error(y_test, model_guesses)

    lazy_guesses = []
    for example in X_test:
        now = example[0]
        lazy_guesses.append(now)
    lazy_error = mean_absolute_error(y_test, lazy_guesses)

    print(f"model is off by {model_error:.1f} BPM on average")
    print(f"lazy guess is off by {lazy_error:.1f} BPM on average")
    if model_error < lazy_error:
        print("the model beats the lazy guess")
    else:
        print("the model does NOT beat the lazy guess, so it hasn't learned anything useful yet")
    print("weights [now, change]:", model.coef_)
    print("bias:", model.intercept_)


def c_array(numbers):
    parts = []
    for number in numbers:
        parts.append(f"{number:.6f}f")
    return "{" + ", ".join(parts) + "}"


def save(model):
    lines = [
        "// Generated by ml/train.py. Don't edit, retrain instead.",
        "#pragma once",
        f"const int MODEL_WINDOW = {WINDOW};",
        f"const int MODEL_AHEAD = {AHEAD};",
        f"const float MODEL_W[] = {c_array(model.coef_)};",
        f"const float MODEL_B = {model.intercept_:.6f}f;",
    ]
    with open("include/model.h", "w") as f:
        f.write("\n".join(lines) + "\n")


assert features([60, 60, 60, 60, 60, 60, 60, 60, 60, 60]) == [60, 0], "a flat 60 BPM should give [60, 0]"
assert features([60, 61, 62, 63, 64, 65, 66, 67, 68, 69]) == [69, 9], "rising 60 to 69 should give [69, 9]"

recordings = load()
assert len(recordings) >= 2, "need at least 2 recordings of 30+ seconds each (lift your finger between them)"

X_train, y_train = make_xy(recordings[:-1])
X_test, y_test = make_xy([recordings[-1]])
print(len(X_train), "training examples,", len(X_test), "test examples")

model = train(X_train, y_train)
test(model, X_test, y_test)
save(model)
print("wrote include/model.h")
